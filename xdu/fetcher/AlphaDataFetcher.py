class AlphaDataFetcher:
    def __init__(self, start_month: str, end_month: str, api_key: str = None):
        """
        Initialize the AlphaDataFetcher with a month range and API key.
        
        Parameters:
        - start_month (str): Start month in 'YYYY-MM' format (e.g., '2009-01').
        - end_month (str): End month in 'YYYY-MM' format (e.g., '2009-12').
        - api_key (str): Alpha Vantage API key. If None, it will be loaded from environment variables.
        """
        self.start_month = start_month
        self.end_month = end_month
        self.api_key = api_key if api_key else os.getenv('ALPHA_VANTAGE_API_KEY')
        if not self.api_key:
            raise ValueError("API key not provided and not found in environment variables.")
        self.base_url = "https://www.alphavantage.co/query"

    def create_month_range(self) -> List[str]:
        """
        Generate a range of months between start_month and end_month.
        
        Returns:
        - List[str]: List of months in 'YYYY-MM' format.
        """
        # Generate a range of months between start_month and end_month
        month_range = pd.date_range(start=self.start_month, end=self.end_month, freq='MS').tolist()
        # Convert each Timestamp to string in 'YYYY-MM' format
        month_range_str = [date.strftime('%Y-%m') for date in month_range]
        return month_range_str

    def get_intraday_data(self, symbol: str, interval: str, month: str, outputsize: str = 'full') -> pd.DataFrame:
        """
        Fetch intraday time series data for a single symbol and month from Alpha Vantage API.
        
        Parameters:
        - symbol (str): Stock symbol (e.g., 'IBM').
        - interval (str): Time interval (e.g., '1min', '5min').
        - month (str): Month in 'YYYY-MM' format (e.g., '2009-01').
        - outputsize (str): 'compact' or 'full' (full retrieves all available data).
        
        Returns:
        - pd.DataFrame: DataFrame containing the intraday data.
        """
        # Construct the API URL
        url = f'https://www.alphavantage.co/query?function=TIME_SERIES_INTRADAY&symbol={symbol}&interval={interval}&month={month}&outputsize=full&apikey={self.api_key}&datatype=csv'

        print(f"URL: {url}")

        try:
            # Make the API request
            response = requests.get(url)

            response.raise_for_status()
            
            print(response.text)
            
            # Parse CSV data into a DataFrame
            df = pd.read_csv(StringIO(response.text), index_col='timestamp', parse_dates=True)
            
            # Rename columns to match expected structure
            df.columns = ['open', 'high', 'low', 'close', 'volume']
            
            # Ensure data is in float format
            df = df.astype({'open': float, 'high': float, 'low': float, 'close': float, 'volume': int})
            
            # Add a 'symbol' column
            df['symbol'] = symbol
            
            # Sort by timestamp descending (most recent first)
            return df.sort_index(ascending=False)

        except requests.exceptions.RequestException as e:
            print(f"Error fetching data for {symbol} - {month}: {e}")
            return pd.DataFrame()  # Return empty DataFrame on error
        except pd.errors.EmptyDataError:
            print(f"No data returned for {symbol} - {month}")
            return pd.DataFrame()

    def fetch_multiple_symbols(self, symbols: List[str], interval: str = '1min', 
                              outputsize: str = 'full', save_to_csv: bool = True) -> pd.DataFrame:
        """
        Fetch intraday data for multiple symbols over a range of months and combine into a single DataFrame.
        
        Parameters:
        - symbols (List[str]): List of stock symbols (e.g., ['IBM', 'AAPL']).
        - interval (str): Time interval (e.g., '1min', '5min').
        - outputsize (str): 'compact' or 'full'.
        - save_to_csv (bool): Whether to save the combined data to a CSV file.
        
        Returns:
        - pd.DataFrame: Combined DataFrame with data for all symbols.
        """
        all_data = []
        months = self.create_month_range()  # Use the month range generated by create_month_range

        # Create a directory to save CSV files if needed
        if save_to_csv:
            dfp = "./data/alpha_data"
            if not os.path.exists(dfp):
                os.makedirs(dfp)

        # Fetch data for each symbol and month
        for symbol in symbols:
            symbol_data = []
            for month in months:
                print(f"Fetching data for {symbol} - {month}...")
                df = self.get_intraday_data(symbol, interval, month, outputsize)
                if not df.empty:
                    symbol_data.append(df)
                
                # Delay to respect API rate limits (5 requests per minute for free tier)
                sleep(20)  # 12 seconds ensures < 5 requests/minute

            # Combine data for the symbol across all months
            if symbol_data:
                combined_symbol_df = pd.concat(symbol_data)
                all_data.append(combined_symbol_df)

        # Combine data for all symbols into a single DataFrame
        if all_data:
            final_df = pd.concat(all_data)
            final_df = final_df.sort_index(ascending=False)  # Sort by timestamp

            # Save to CSV if requested
            if save_to_csv:
                file_path = "{dfp}/combined_{interval}_data.csv"
                final_df.to_csv(file_path)
                print(f"Saved combined data to {file_path}")

            return final_df
        else:
            print("No data fetched.")
            return pd.DataFrame()

